import AppKit

final class ClipboardHistory {
    static let shared = ClipboardHistory()
    static let pluginID = "tech.simplife.clipboard-history"

    struct Snapshot: Encodable, Equatable {
        let authorized: Bool
        let recording: Bool
        let entries: [Entry]
    }

    struct Entry: Encodable, Equatable {
        let id: UUID
        let text: String
    }

    private var authorizedPlugin: StickerPlugin?
    private var requestingPermission = false
    private var timer: Timer?
    private var entries: [Entry] = []
    private var changeCount = 0
    private let pasteboard = NSPasteboard.general
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType"
    ]

    func snapshot(for plugin: StickerPlugin) -> Snapshot {
        let authorized = authorizedPlugin == plugin
        return Snapshot(authorized: authorized, recording: authorized && timer != nil,
                        entries: authorized ? entries : [])
    }

    func start(for plugin: StickerPlugin) {
        guard plugin.id == Self.pluginID, timer == nil, !requestingPermission else { return }
        if authorizedPlugin != plugin {
            requestingPermission = true
            defer { requestingPermission = false }
            let alert = NSAlert()
            alert.messageText = L10n.text("允许记录剪贴板？")
            alert.informativeText = L10n.text("此插件可以读取本次运行期间复制的纯文本，内容可能包含敏感信息。最近 50 条仅保存在内存中。")
            alert.addButton(withTitle: L10n.text("允许"))
            alert.addButton(withTitle: L10n.text("取消"))
            NSApp.activate(ignoringOtherApps: true)
            guard alert.runModal() == .alertFirstButtonReturn,
                  StickerPluginRegistry.shared.plugins.contains(plugin) else { return }
            authorizedPlugin = plugin
        }
        changeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.capture() }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func pause(for plugin: StickerPlugin) {
        guard authorizedPlugin == plugin else { return }
        stop()
    }

    func clear(for plugin: StickerPlugin) {
        guard authorizedPlugin == plugin else { return }
        entries.removeAll()
        changeCount = pasteboard.changeCount
    }

    func copy(_ id: UUID, for plugin: StickerPlugin) {
        guard authorizedPlugin == plugin, let entry = entries.first(where: { $0.id == id }) else { return }
        copyToClipboard(entry.text)
        changeCount = pasteboard.changeCount
    }

    func reconcile(installed: [StickerPlugin]) {
        guard let authorizedPlugin else { return }
        guard let updated = installed.first(where: {
            $0.isUpdate(of: authorizedPlugin)
        }) else {
            reset()
            return
        }
        self.authorizedPlugin = updated
    }

    func reset() {
        stop()
        entries.removeAll()
        authorizedPlugin = nil
    }

    private func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func capture() {
        let current = pasteboard.changeCount
        guard current != changeCount else { return }
        changeCount = current
        guard let items = pasteboard.pasteboardItems,
              items.allSatisfy({ item in item.types.allSatisfy { !ignoredTypes.contains($0.rawValue) } }),
              let value = pasteboard.string(forType: .string),
              pasteboard.changeCount == current, !value.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              value.utf8.count <= 32_768 else { return }
        if entries.first?.text == value { return }
        entries.removeAll { $0.text == value }
        entries.insert(Entry(id: UUID(), text: value), at: 0)
        if entries.count > 50 { entries.removeLast(entries.count - 50) }
    }
}
